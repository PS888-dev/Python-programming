# Wildcard Pattern กำหนดกระบวนการทำงานกรณีที่ค่าตัวแปรไม่ตรงกับค่าคงที่ที่กำหนดไว้ ใช้_

service=2
match service:
    case 1:
        print("ฝากเงิน")
    case 2:
        print("ถอนเงิน")
    case 3:
        print("สอบถามยอดเงินคงเหลือ")
    case _: #กรณีที่ค่าตัวแปรไม่ตรงกับค่าคงที่ที่กำหนดไว้
        print("หมายเลขบริการไม่ถูกต้อง")
