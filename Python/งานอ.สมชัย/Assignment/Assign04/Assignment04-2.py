e = float(input("ค่าเเรงดันไฟฟ้า :"))
r1 = float(input("ค่าความต้านทานตัวที่ 1 (R1) :"))
r2 = float(input("ค่าความต้านทานตัวที่ 2 (R2) :"))
r3 = float(input("ค่าความต้านทานตัวที่ 3 (R3) :"))

i = e / (r1 + r2 + r3)
v1 = i * r1
v2 = i * r2
v3 = i * r3

print(f"กระแสไฟฟ้ารวม = {i:.2f}")
print(f"แรงดันตกคร่อม R1 = {v1:.2f} V")
print(f"แรงดันตกคร่อม R2 = {v2:.2f} V")
print(f"แรงดันตกคร่อม R3 = {v3:.2f} V")